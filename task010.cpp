#include <iostream>
#include <vector>
#include <iomanip>
#include <algorithm>
#include <cmath>
#include <set>
#include <string>
#include <map>




int main() {
	std::ios_base::sync_with_stdio(false);
	std::cin.tie(NULL);
	long long n, k; long long a, b, c;
	std::cin >> n >> k;
	long long min1 = 99999999999;
	long long max1 = -99999999999;
	std::vector<std::vector <long long>> K(n); //список списков там будет для каждой лягушки начальная прыжок и масса
	for (int i = 0; i < n; i++) {
		std::cin >> a >> b >> c;
		if (a < min1) {
			min1 = a; //обновляем минимум если начальная координата меньше
		}
		if (a > max1) {
			max1 = a; //аналогично максимум
		}
		K[i] = { a,b,c }; // пока в список кидаем начальную смещение и массу потом сделаем что надо
	}
	//всего будет 3 случая первый когда все на местах просто, второй когда одна прыгает только(ну то есть она
	//определяет расстояние максимальное
	//и третий когда двое определяют макс расстояние
	long long nashli1 = max1 - min1; // и пока в переменную нашли1 запишем наше первое расстояние когда все на месте
	std::multiset<long long> W;
	for (int i = 0; i < n;i++) {
		W.insert(K[i][0]); // закидываем в W начальные координаты (мультисет потому что могут совпадать)
	}
	long long nashli2 = 0;
	for (int i = 0; i < n;i++) { //летим по массиву
		if (K[i][2] <= k) {//ТОЛЬКО если масса меньше или равно k
			W.erase(W.find(K[i][0])); // добавляем
			long long kk = K[i][0] + K[i][1]; //считаем координату в которую она прыгнет
			W.insert(kk); // и добавляем эту координату
			nashli2 = std::max(nashli2, *W.rbegin() - *W.begin()); //обновляем максимум
			W.erase(W.find(kk));//выкидываем обратно расстояние
			W.insert(K[i][0]);//и возвращаем начальную координату
		}
		else {
			continue; //если масса больше чем k то не можем ничо сделать(она в принципе не может прыгать) просто идем дальше
		}
	}
	long long nashli12 = std::max(nashli1, nashli2); //промежуточный максимум пока что среди первых двух случаев
	std::vector <std::vector<long long>> A;
	for (int i = 0;i < n;i++) {
		if (K[i][2] <= k) {
			A.push_back({ K[i][2], K[i][0] + K[i][1], 0,0 });
		}
	}
	std::sort(A.begin(), A.end());
	if (!A.empty()) { //на случай если а пустой
		A[0][2] = A[0][1]; //для нулевого элемента заполняем сразу
		A[0][3] = A[0][2];
		for (int i = 1; i < A.size(); i++) {
			A[i][2] = std::min(A[i][1], A[i - 1][2]); //префиксный минимум
			A[i][3] = std::max(A[i][1], A[i - 1][3]); //префиксный максимум
		}
		//теперь в А лежат (масса, конечн. коорд., пр минимум, пр максимум)
		long long nashli3 = 0;
		for (int i = 1;i < A.size(); i++) {//идем по всем лягушкам
			long long ost = k - A[i][0]; //находим массу которая остается для второй
			long long l = 0; //границы л=0
			long long r = i - 1;//r=прошлая лягушка потому что позже нее не берем
			long long p = -1;//пока -1 вдруг не найдем
			while (l <= r) {
				long long M = (l + r) / 2; //бинпоиском ищем последнюю лягушку с нужной массой
				if (A[M][0] <= ost) {
					l = M + 1; p = M; //если нашли пробуем вдруг есть тяжелее
				}
				else {
					r = M - 1; //если нет двигаем правую границу
				}
			}
			if (p != -1) { //если только p поменялся то записываем в мм максимум
				long long mm = std::max(abs(A[i][1] - A[p][2]), abs(A[i][1] - A[p][3]));
				nashli3 = std::max(nashli3, mm); //и потом среди того что было и нового мм максимум
			}
		}
		std::cout << std::max(nashli3, nashli12) << "\n"; return 0; //итоговый максимум

	}
	else { //если А пустой то никто прыгать не может все стоят на месте забираем просто нашли12
		std::cout << nashli12 << "\n"; return 0;
	}



}





